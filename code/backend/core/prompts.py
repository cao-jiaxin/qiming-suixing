# ----------------  距离数据的结构化注入（F03 核心机制）  ----------------


def build_distance_block(distances: list) -> str:
    """把深度模块的输出渲染成给大模型的结构化文本。

    distances 形如：[{"bearing": "12点", "steps": 5, "kind": "obstacle", ...}]
    （由 core/depth.py 产出，字段名以此为准）

    这是抑制距离幻觉的核心动作：提示词里明确写"只能引用，不得估算"。
    """
    if not distances:
        return "（本次未取得可靠距离数据，所有距离一律写「距离不明」，禁止报出任何步数或米数）"
    lines = []
    for d in distances:
        bearing = d.get("bearing") or d.get("zone") or "12点"
        steps = d.get("steps")
        kind = d.get("kind", "obstacle")
        kind_cn = "障碍" if kind == "obstacle" else "物体"
        lines.append(f"- {bearing}方向，约 {steps} 步处有{kind_cn}")
    return "（以下数据由深度模型实测得出，只能原文引用，不得修改数值、不得自行估算）：\n" + "\n".join(lines)
