"""生成三张项目管理表（功能清单 / 评测集设计 / 逐日排期）

用途：
    python code/make_tables.py

产出（写到 results/）：
    1. 功能清单.csv       —— 决定"做什么、不做什么"，也是范围控制的抓手
    2. 评测集设计.csv      —— 决定答辩时"凭什么说我们做得好"
    3. 逐日排期.csv        —— 从今天到 10/10 提交，逐日有人在干什么

产出内容同时也是设计文档第三、四章的数据来源，改表即可同步改文档。

为什么单独一个脚本：
    ——这三张表会被反复改，用脚本生成保证列名和结构稳定，
      也方便直接把 results/*.csv 贴进Excel做答辩用图。
"""
from __future__ import annotations

import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "results"
OUT.mkdir(parents=True, exist_ok=True)


def smoke_summary() -> str:
    """从 results/smoke_test_result.json 读最新通过数。

    不把"36/36"这类数字写死在表里：测试用例会增加，写死的数字迟早过时，
    而这张表是设计文档第三、四章的数据来源——文档里的数字与实测对不上，
    评审一核对就露馅。宁可动态读一次。
    """
    try:
        d = json.loads((OUT / "smoke_test_result.json").read_text(encoding="utf-8"))
        return f"{d['passed']}/{d['total']} 通过"
    except Exception:
        return "待跑（python code/backend/smoke_test.py）"


def write_csv(name: str, header: list[str], rows: list[list[str]]) -> Path:
    p = OUT / name
    # utf-8-sig 让 Excel 双击直接打开中文不乱码
    with p.open("w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(header)
        w.writerows(rows)
    return p


